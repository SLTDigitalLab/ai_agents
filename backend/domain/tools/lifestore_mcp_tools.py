def _compact_product(product: dict[str, Any]) -> dict[str, Any]:
    """
    Keep only the fields the LLM needs to answer safely.

    This prevents ToolNode from sending huge raw product payloads back into
    the model and reduces the chance of mixed-up product details.
    """
    key_details = product.get("key_details") or []
    if not isinstance(key_details, list):
        key_details = []

    vector_evidence = product.get("vector_evidence") or []
    if not isinstance(vector_evidence, list):
        vector_evidence = []

    compact = {
        "product_id": product.get("product_id"),
        "name": product.get("name"),
        "seller": product.get("seller"),
        "brand": product.get("brand"),
        "category": product.get("category"),
        "product_type": product.get("product_type"),
        "price": product.get("price"),
        "price_value": product.get("price_value"),
        "currency": product.get("currency"),
        "stock_status": product.get("stock_status") or product.get("availability"),
        "stock": product.get("stock"),
        "url": product.get("url"),
        "image_url": product.get("image_url"),
        "image_available": product.get("image_available"),
        "image_source": product.get("image_source"),
        "description": _limit_text(product.get("description"), 700),
        "key_details": [_limit_text(item, 220) for item in key_details[:6]],
        "vector_evidence": [_limit_text(item, 500) for item in vector_evidence[:3]],
    }

    return {
        key: value
        for key, value in compact.items()
        if value not in (None, "", [], {})
    }



