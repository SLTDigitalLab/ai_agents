def _mcp_auth_headers() -> dict[str, str]:
    """
    Build optional authentication headers for backend -> MCP communication.

    In staging/production, set:
        LIFESTORE_MCP_TOKEN=<strong-random-token>

    The backend will send:
        Authorization: Bearer <token>

    If the token is not configured, no auth header is sent. This keeps local
    development flexible, while allowing secured staging/production deployments.
    """
    token = os.getenv("LIFESTORE_MCP_TOKEN", "").strip()

    if not token:
        return {}

    return {
        "Authorization": f"Bearer {token}",
    }


def _get_mcp_client() -> Any:
    """
    Create the real MCP client used by the LangGraph tool wrappers.

    Supports two production modes:
    1. stdio: backend launches the MCP server through lifestore_mcp_launcher.py
    2. streamable_http: backend connects to a persistent MCP server URL

    Security:
    - For streamable_http mode, if LIFESTORE_MCP_TOKEN is set, the backend sends
      it as a Bearer token to the MCP server.
    """
    global _MCP_CLIENT

    if MultiServerMCPClient is None:
        raise RuntimeError(
            "langchain_mcp_adapters is not installed. Run: "
            "pip install -U 'langchain-mcp-adapters>=0.3.0' 'mcp>=1.27,<2'"
        )

    if _MCP_CLIENT is not None:
        return _MCP_CLIENT

    transport = os.getenv("LIFESTORE_MCP_TRANSPORT", "stdio").strip().lower()

    if transport in {"streamable_http", "streamable-http", "http"}:
        mcp_url = os.getenv("LIFESTORE_MCP_URL", "http://127.0.0.1:8001/mcp").strip()

        server_config: dict[str, Any] = {
            "transport": "streamable_http",
            "url": mcp_url,
        }

        auth_headers = _mcp_auth_headers()
        if auth_headers:
            server_config["headers"] = auth_headers

        _MCP_CLIENT = MultiServerMCPClient(
            {
                "lifestore": server_config,
            }
        )
        return _MCP_CLIENT

    launcher = os.getenv("LIFESTORE_MCP_LAUNCHER", str(MCP_LAUNCHER_PATH))

    if not Path(launcher).exists():
        raise FileNotFoundError(f"LifeStore MCP launcher not found at: {launcher}")

    _MCP_CLIENT = MultiServerMCPClient(
        {
            "lifestore": {
                "transport": "stdio",
                "command": os.getenv("LIFESTORE_MCP_COMMAND", sys.executable),
                "args": [launcher],
            }
        }
    )

    return _MCP_CLIENT

async def _get_mcp_tool_map() -> dict[str, Any]:
    """
    Load MCP tools from the LifeStore MCP server and cache them.

    The returned tools are LangChain-compatible wrappers generated by
    langchain_mcp_adapters from the real MCP server.
    """
    global _MCP_TOOLS_CACHE

    if _MCP_TOOLS_CACHE is not None:
        return _MCP_TOOLS_CACHE

    client = _get_mcp_client()
    tools = await client.get_tools()

    _MCP_TOOLS_CACHE = {item.name: item for item in tools}
    return _MCP_TOOLS_CACHE


def _safe_text(value: Any) -> str:
    if value is None:
        return ""
    return str(value).strip()


def _json_default(value: Any) -> str:
    try:
        return str(value)
    except Exception:
        return "<unserializable>"


def _limit_text(value: Any, max_chars: int = 700) -> str:
    text = _safe_text(value)
    if len(text) <= max_chars:
        return text
    return text[:max_chars].rstrip() + "..."


def _extract_text_from_content_block(block: Any) -> str:
    """
    MCP adapter results can be plain strings, dicts, content blocks, or objects.
    This makes the result parsing defensive.
    """
    if block is None:
        return ""

    if isinstance(block, str):
        return block

    if isinstance(block, dict):
        for key in ["text", "content", "value", "result"]:
            if key in block:
                return _safe_text(block.get(key))
        return json.dumps(block, ensure_ascii=False, default=_json_default)

    for attr in ["text", "content", "value"]:
        if hasattr(block, attr):
            return _safe_text(getattr(block, attr))

    return _safe_text(block)


def _try_parse_json_text(text: str) -> Any:
    text = _safe_text(text)

    if not text:
        return None

    try:
        return json.loads(text)
    except Exception:
        pass

    # Some tool wrappers may return readable text around JSON.
    start = text.find("{")
    end = text.rfind("}")

    if start >= 0 and end > start:
        try:
            return json.loads(text[start : end + 1])
        except Exception:
            return None

    return None


def _coerce_mcp_result(raw: Any) -> dict[str, Any]:
    """
    Convert a raw MCP adapter return value into a dictionary.
    """
    if isinstance(raw, dict):
        return raw

    if isinstance(raw, list):
        joined = "\n".join(
            part
            for part in (_extract_text_from_content_block(item) for item in raw)
            if part
        )
        parsed = _try_parse_json_text(joined)
        if isinstance(parsed, dict):
            return parsed
        return {"status": "success", "text": joined, "raw_result": joined}

    parsed = _try_parse_json_text(_extract_text_from_content_block(raw))
    if isinstance(parsed, dict):
        return parsed

    return {
        "status": "success",
        "text": _extract_text_from_content_block(raw),
        "raw_result": _extract_text_from_content_block(raw),
    }


async def _call_mcp_tool(tool_name: str, **kwargs: Any) -> dict[str, Any]:
    """
    Call a real MCP server tool through langchain_mcp_adapters.

    This is the key Option B change:
    - No importlib
    - No direct Python function call
    - Tool call goes through MCP client -> MCP server -> tool
    """
    try:
        tool_map = await _get_mcp_tool_map()
        mcp_tool = tool_map.get(tool_name)

        if mcp_tool is None:
            return {
                "status": "error",
                "message": f"MCP tool '{tool_name}' was not found on the LifeStore MCP server.",
                "available_tools": sorted(tool_map.keys()),
            }

        raw_result = await mcp_tool.ainvoke(kwargs)
        result = _coerce_mcp_result(raw_result)

        if "status" not in result:
            result["status"] = "success"

        return result

    except Exception as exc:
        return {
            "status": "error",
            "message": str(exc),
            "tool_name": tool_name,
            "mcp_launcher_path": str(MCP_LAUNCHER_PATH),
        }


