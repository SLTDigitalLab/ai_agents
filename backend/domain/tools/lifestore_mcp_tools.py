def _is_valid_product_card_image(product: dict[str, Any]) -> bool:
    url = _safe_text(product.get("image_url")).lower()

    if not url.startswith(("http://", "https://")):
        return False

    if url.endswith(".svg") or url.startswith("data:"):
        return False

    if any(marker in url for marker in BAD_PRODUCT_CARD_IMAGE_MARKERS):
        return False

    return "/sites/default/files/" in url or any(
        ext in url for ext in [".jpg", ".jpeg", ".png", ".webp", ".gif"]
    )


def _infer_display_mode(result: dict[str, Any], products: list[dict[str, Any]]) -> str:
    frontend_contract = result.get("frontend_contract")
    if isinstance(frontend_contract, dict):
        display = _safe_text(frontend_contract.get("display"))
        render_as = _safe_text(frontend_contract.get("render_as")).lower()
        if display:
            return display
        if "comparison" in render_as:
            return "comparison"

    if len(products) <= 1:
        return "single"
    return "carousel"


def _build_product_cards(products: list[dict[str, Any]], limit: int) -> list[dict[str, Any]]:
    cards: list[dict[str, Any]] = []
    for product in products:
        if _is_valid_product_card_image(product):
            cards.append(product)
        if len(cards) >= max(int(limit), 1):
            break
    return cards

def _extract_products(result: dict[str, Any], limit: int = 5) -> list[dict[str, Any]]:
    """
    MCP tools may return products in different shapes:
    - products
    - returned_products
    - product
    - order.items
    """
    if int(limit or 0) <= 0:
        return []

    products: list[dict[str, Any]] = []

    raw_products = result.get("products")
    if isinstance(raw_products, list):
        products.extend(item for item in raw_products if isinstance(item, dict))

    returned_products = result.get("returned_products")
    if isinstance(returned_products, list):
        products.extend(item for item in returned_products if isinstance(item, dict))

    single_product = result.get("product")
    if isinstance(single_product, dict):
        products.append(single_product)

    order = result.get("order")
    if isinstance(order, dict):
        order_items = order.get("items")
        if isinstance(order_items, list):
            products.extend(item for item in order_items if isinstance(item, dict))

    deduped: list[dict[str, Any]] = []
    seen: set[str] = set()

    for product in products:
        key = (
            _safe_text(product.get("url"))
            or _safe_text(product.get("product_id"))
            or _safe_text(product.get("name")).lower()
        )

        if not key or key in seen:
            continue

        seen.add(key)
        deduped.append(_compact_product(product))

        if len(deduped) >= max(int(limit), 1):
            break

    return deduped


def _compact_result(
    result: dict[str, Any],
    *,
    product_limit: int = 5,
    include_answer: bool = True,
    include_categories: bool = False,
) -> dict[str, Any]:
    """
    Normalize MCP responses into a compact structure for the LLM.

    Important frontend rule:
    - `products` is the source for the visible answer/table.
    - `product_cards` is the image-safe subset the LLM should place inside
      [LIFESTORE_PRODUCT_CARDS] so broad queries still render a slideshow.
    """
    compact: dict[str, Any] = {
        "status": result.get("status"),
        "message": result.get("message"),
        "text": result.get("text"),
        "query": result.get("query"),
        "retrieval_query": result.get("retrieval_query"),
        "product_query": result.get("product_query"),
        "requested_availability": result.get("requested_availability"),
        "actual_availability": result.get("actual_availability"),
        "matches_requested_availability": result.get("matches_requested_availability"),
        "retrieval": result.get("retrieval"),
    }

    if include_answer:
        compact["answer"] = _limit_text(result.get("answer"), 1800)

    products = _extract_products(result, limit=product_limit)
    if products:
        display = _infer_display_mode(result, products)
        product_cards = _build_product_cards(products, limit=product_limit)

        compact["products"] = products
        compact["display"] = display
        compact["product_cards"] = product_cards
        compact["product_card_instruction"] = (
            "If product_cards is non-empty, always append a hidden "
            "[LIFESTORE_PRODUCT_CARDS] block using product_cards. "
            "Use display as the block display value. The visible table must use "
            "the same final products list returned by the MCP tool; do not add "
            "extra semantic matches or accessories that are not in products."
        )

    if include_categories:
        categories = result.get("categories")
        if isinstance(categories, list):
            compact["categories"] = categories[:80]

    frontend_contract = result.get("frontend_contract")
    if isinstance(frontend_contract, dict):
        compact["frontend_contract"] = frontend_contract

    return {
        key: value
        for key, value in compact.items()
        if value not in (None, "", [], {})
    }


def _to_tool_json(payload: dict[str, Any]) -> str:
    """
    LangGraph ToolNode sends tool results back to the LLM as ToolMessages.
    Returning JSON text keeps the result readable and predictable.
    """
    return json.dumps(payload, ensure_ascii=False, indent=2, default=_json_default)


def _parse_product_queries(product_queries: str) -> list[str]:
    """
    Accept either:
    - JSON list: ["Product A", "Product B"]
    - comma-separated text: Product A, Product B
    """
    text = _safe_text(product_queries)

    if not text:
        return []

    try:
        parsed = json.loads(text)
        if isinstance(parsed, list):
            return [_safe_text(item) for item in parsed if _safe_text(item)]
    except Exception:
        pass

    return [_safe_text(item) for item in text.split(",") if _safe_text(item)]


