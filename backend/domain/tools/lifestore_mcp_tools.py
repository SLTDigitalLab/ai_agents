@tool
async def lifestore_create_draft_order_tool(
    cart_json: str,
    currency: str = "LKR",
) -> str:
    """
    Create a local LifeStore draft order through the LifeStore MCP server.

    Use this only when the user has clearly selected product(s) and wants to
    proceed with an order. This does not place a real order and does not create
    a real payment link.

    cart_json should be a JSON list:
    [
      {"name": "COMSTOX ZLT T10 Max 4G LTE Router", "quantity": 1}
    ]
    """
    try:
        cart = json.loads(cart_json)
    except Exception:
        return _to_tool_json(
            {
                "status": "invalid_cart_json",
                "message": "cart_json must be a valid JSON list of cart items.",
            }
        )

    result = await _call_mcp_tool(
        "lifestore_create_order",
        cart=cart,
        currency=currency,
    )

    return _to_tool_json(
        _compact_result(
            result,
            product_limit=8,
            include_answer=False,
        )
    )


