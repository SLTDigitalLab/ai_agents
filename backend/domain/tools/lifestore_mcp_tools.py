    result = await _call_mcp_tool(
        "lifestore_search_products",
        q=query,
        category=category or None,
        min_price=min_price,
        max_price=max_price,
        in_stock_only=in_stock_only,
        sort=sort,
        limit=bounded_limit,
        cursor=0,
        currency="LKR",
    )

    return _to_tool_json(
        _compact_result(
            result,
            product_limit=bounded_limit,
            include_answer=False,
        )
    )


