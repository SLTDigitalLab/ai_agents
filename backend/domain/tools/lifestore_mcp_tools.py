@tool
async def lifestore_hybrid_product_search_tool(
    query: str,
    limit: int = 5,
    include_vector_evidence: bool = False,
    search_mode: str = "auto",
    product_query: str = "",
) -> str:
    """
    Search LifeStore products through the LifeStore MCP server.

    Use this for broad LifeStore product searches, category browsing,
    recommendations, and general product questions.
    """
    bounded_limit = max(min(int(limit or 8), 24), 1)

    result = await _call_mcp_tool(
        "lifestore_hybrid_product_search",
        query=query,
        limit=bounded_limit,
        include_vector_evidence=include_vector_evidence,
        search_mode=search_mode,
        product_query=product_query or None,
    )

    return _to_tool_json(
        _compact_result(
            result,
            product_limit=bounded_limit,
            include_answer=True,
        )
    )


